func hexValue(c: char): uint8 =
  case c
  of 'a'..'f':
    uint8(ord(c) - ord('a') + 10)
  of 'A'..'F':
    uint8(ord(c) - ord('A') + 10)
  else:
    uint8(ord(c) - ord('0'))

func color3v*(r, g, b: uint8): Color = color3b(r, g, b)
func color4v*(r, g, b, a: uint8): Color = color4b(r, g, b, a)
func color4v*(value: Color): Vec4 = unpackUnorm4x8(value)
func `r`*(c: Color): byte = byte(c and 0xff)
func `g`*(c: Color): byte = byte((c shr 8) and 0xff)
func `b`*(c: Color): byte = byte((c shr 16) and 0xff)
func `a`*(c: Color): byte = byte((c shr 24) and 0xff)

