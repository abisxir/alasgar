proc toColor*(color: string): Color =
  let
    start = if color.len > 0 and color[0] == '#': 1 else: 0
    size = color.len - start

  if start == 0 and color.len > 0 and color[0].ord > '9'.ord:
    let name = color.toLowerAscii()
    for entry in webColorMap:
      if name == entry[0]:
        return entry[1]

  if size notin [3, 4, 6, 8]:
    raise newException(ValueError, "Hex color must be RGB, RGBA, RRGGBB, or RRGGBBAA")

  var value = 0'u32
  for index in start..<color.len:
    value = value shl 4 or hexValue(color[index]).uint32

  if size <= 4:
    var bytes: array[4, uint8]
    for i in 0..<size:
      let nibble = ((value shr ((size - 1 - i) * 4)) and 0xF).uint8
      bytes[i] = nibble shl 4 or nibble
    if size == 3:
      result = color3b(bytes[0], bytes[1], bytes[2])
    else:
      result = color4b(bytes[0], bytes[1], bytes[2], bytes[3])
  else:
    if size == 6:
      result = color3b(
        ((value shr 16) and 0xFF).uint8,
        ((value shr 8) and 0xFF).uint8,
        (value and 0xFF).uint8,
      )
    else:
      result = color4b(
        ((value shr 24) and 0xFF).uint8,
        ((value shr 16) and 0xFF).uint8,
        ((value shr 8) and 0xFF).uint8,
        (value and 0xFF).uint8,
      )

func toHex*(c: Color): string =
  result = newString(8)
  for i in 0..7:
    let nibble = ((c shr ((7 - i) * 4)) and 0xF).uint8
    result[i] = (if nibble < 10: char(ord('0') + nibble) else: char(ord('a') + nibble - 10))

converter stringToColor*(color: string): Color = toColor(color)
converter vec4ToColor*(v: Vec4): Color = color4f(v.x, v.y, v.z, v.w)
